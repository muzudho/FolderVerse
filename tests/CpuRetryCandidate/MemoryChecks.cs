w.Robots.Initialize(w.Nodes.All.Length,w.ActiveCount);w.Robots.ConfigureFactories(w);
foreach(var n in w.Nodes.All)n.Owner=0;
int source=0,target=1;w.Nodes.All[target].Owner=2;
var defender=w.Robots.Create(2,RobotParts.Complete);w.Robots.Nodes[target].Add(defender);
var b=new BattleState(1,new()){Kind=BattleKind.Node};
b.AddArmy(0,source,new[]{new Robot(10001,0,RobotParts.Complete),new Robot(10002,0,RobotParts.Complete)});
b.AddArmy(2,target,new[]{defender});b.Finished=true;b.Winner=2;
var e=new RobotEncounter{Id=10,Target=target,Defender=2,Finished=true};e.Battles.Add(b);
var campaign=w.Campaign.RobotBattles;campaign.Encounters.Add(e);campaign.ObserveCpuAssaultFailures(w);
Check(campaign.CpuFailedForce(w,0,target)==2,"Conventional defeat is remembered without no-will retreat");
campaign.Encounters.Clear();campaign.ObserveCpuAssaultFailures(w);
Check(campaign.CpuFailedForce(w,0,target)==2,"Memory survives encounter removal");
AutoSaveStore.Write(args[0],w);var restored=AutoSaveStore.Read<WorldSetup>(args[0]);
Check(restored.Campaign.RobotBattles.CpuFailedForce(restored,0,target)==2,"Memory survives save/resume");
typeof(PopulationSimulation).GetProperty("Turn")!.SetValue(restored.Population,13);
Check(restored.Campaign.RobotBattles.CpuFailedForce(restored,0,target)==0,"Memory expires instead of blocking forever");
Check(campaign.CpuFailedForce(w,1,target)==0,"Independent country does not inherit failure");
w.Robots.Nodes[target].Remove(defender.Id);
Check(campaign.CpuFailedForce(w,0,target)==0,"Weakened defense permits retry");
w.Robots.Nodes[target].Add(defender);w.Nodes.All[target].Owner=1;
